import type { Metadata, Viewport } from 'next';
import './globals.css';
import { siteOrigin } from '@/config/site';
import { networkLabel } from '@/config/landing';
import { THEME_COLOR, THEME_SCRIPT } from '@/components/landing/theme';

// The root layout is deliberately thin: it renders on every route, including the landing page,
// which has a hard JS and font budget. App-only pieces live where they're used:
// - the app theme (app.css), the wallet providers, framer-motion's MotionConfig and the Toaster:
//   (app)/layout.tsx. Both route groups use the landing's two font files (no Inter / Space Grotesk).
const TITLE = 'DappDrop: Web3 quest campaigns with rewards in on-chain escrow';
const DESCRIPTION = `Run token and NFT reward campaigns with on-chain escrow. Reward lists are public for 24 hours before claims open. Public beta on ${networkLabel}.`;

export const metadata: Metadata = {
    title: TITLE,
    description: DESCRIPTION,
    // S1-15: share cards. The images are src/app/opengraph-image.png / twitter-image.png (+ .alt.txt),
    // generated by scripts/generate-og-image.mjs.
    openGraph: { type: 'website', siteName: 'DappDrop', title: TITLE, description: DESCRIPTION, url: '/' },
    twitter: { card: 'summary_large_image', title: TITLE, description: DESCRIPTION },
    // Absolute URLs (canonical, OG) resolve against the official domain (src/config/site.ts).
    metadataBase: new URL(siteOrigin),
    applicationName: 'DappDrop',
    // Icons: src/app/icon.png, apple-icon.png and favicon.ico (file conventions), typeset from
    // the Newsreader wordmark.
};

// The fallback for routes outside both route groups (the root not-found, which is Monolith-themed
// too). The same values as src/app/(landing)/layout.tsx and src/app/(app)/layout.tsx: Obsidian
// is the default; the CSS color-scheme follows a remembered Porcelain (globals.css).
export const viewport: Viewport = {
    colorScheme: 'dark',
    themeColor: THEME_COLOR.obsidian,
};

export default function RootLayout({
    children,
}: Readonly<{
    children: React.ReactNode;
}>) {
    return (
        <html lang="en" data-theme="obsidian" suppressHydrationWarning>
            <head>
                {/* 07-wow: sets <html data-theme> before first paint (no flash of the wrong theme).
                    Obsidian by default for everyone; Porcelain only when the visitor chose it.
                    The themed tokens apply inside the .lp-theme (marketing, root 404) and
                    .app-theme (app) wrappers. */}
                <script dangerouslySetInnerHTML={{ __html: THEME_SCRIPT }} />
            </head>
            <body className="font-body antialiased min-h-screen flex flex-col bg-background" suppressHydrationWarning>
                {children}
            </body>
        </html>
    );
}
